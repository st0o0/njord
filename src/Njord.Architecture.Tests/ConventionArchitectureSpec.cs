using ArchUnitNET.Domain;
using ArchUnitNET.xUnitV3;
using Njord.Alerts;
using Njord.Indices;
using static ArchUnitNET.Fluent.ArchRuleDefinition;

namespace Njord.Architecture.Tests;

public sealed class ConventionArchitectureSpec
{
    private static readonly string[] TestAttributes = ["Xunit.FactAttribute", "Xunit.TheoryAttribute"];

    private static bool DeclaresTests(Class c)
        => c.Members.OfType<MethodMember>().Any(m => m.Attributes.Any(a => TestAttributes.Contains(a.FullName)));

    [Fact]
    public void Production_classes_are_sealed()
    {
        Classes().That().Are(NjordArchitecture.ProductionTypes)
            .And().AreNotAbstract()
            .And().DoNotHaveName("Program") // compiler-generated by top-level statements in Program.cs; cannot be sealed
            .Should().BeSealed()
            .Check(NjordArchitecture.Instance);
    }

    [Fact]
    public void Test_classes_with_tests_are_sealed_and_suffixed_Spec()
    {
        Classes().That().Are(NjordArchitecture.TestTypes)
            .And().FollowCustomPredicate(DeclaresTests, "declare tests")
            .Should().BeSealed()
            .AndShould().HaveNameEndingWith("Spec")
            .Check(NjordArchitecture.Instance);
    }

    [Theory]
    [InlineData("Enrichment")]
    [InlineData("Computer")]
    [InlineData("Calculator")]
    [InlineData("Scorer")]
    [InlineData("Evaluator")]
    [InlineData("Factory")]
    public void Analysis_type_names_avoid_legacy_name_parts(string namePart)
    {
        Types().That().Are(NjordArchitecture.AnalysisTypes)
            .Should().NotHaveNameContaining(namePart)
            .Check(NjordArchitecture.Instance);
    }

    [Fact]
    public void Alert_rules_live_in_the_alerts_library()
    {
        Classes().That().Are(NjordArchitecture.ProductionTypes)
            .And().ImplementInterface(typeof(IAlertRule))
            .Should().Be(NjordArchitecture.TypesInLibrary("Njord.Alerts"))
            .Check(NjordArchitecture.Instance);
    }

    [Fact]
    public void Index_scores_live_in_the_indices_library()
    {
        Classes().That().Are(NjordArchitecture.ProductionTypes)
            .And().ImplementInterface(typeof(IIndexScore))
            .Should().Be(NjordArchitecture.TypesInLibrary("Njord.Indices"))
            .Check(NjordArchitecture.Instance);
    }
}
